#!/usr/bin/env python3
"""Design tokens: reads design/tokens.json, writes design/tokens.css, and (--check) compares the game's :root colours and fonts to the tokens.
Usage: python3 tools/tokens.py          write design/tokens.css
       python3 tools/tokens.py --check  report drift between the game CSS and the tokens (exit 1 on drift)
Nothing here changes the game. Wiring the tokens into index.src.html waits for Grigor's approval."""
import json, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
T = json.loads((root / "design/tokens.json").read_text())
def css():
    L = {k: v["light"] for k, v in T["color"].items()}
    D = {k: v["dark"] for k, v in T["color"].items()}
    o = ["/* Generated by tools/tokens.py from design/tokens.json. Do not edit by hand. */", ":root{"]
    o += [f"  --{k}:{v};" for k, v in L.items()]
    o += [f"  --{k}:{v['stack']};" for k, v in T["font"].items()]
    o += [f"  --{k}:{v['px']}px;" for k, v in T["type-scale"].items()]
    o += [f"  --{k}:{v}px;" for k, v in T["radius"].items()]
    o += [f"  --{k}:{v}px;" for k, v in T["space"].items()]
    o += [f"  --stroke-{k}:{v};" for k, v in T["stroke"].items()]
    o += [f"  --{k}:{v}px;" for k, v in T["icon"].items()]
    o += [f"  --{k}:{v};" for k, v in T["elevation"].items()]
    o += [f"  --{k}:{v};" for k, v in T["layer"].items()]
    o += ["  color-scheme:light;", "}",
          ":root[data-theme=dark]{" + ";".join(f"--{k}:{D[k]}" for k in D if D[k] != L[k]) + ";color-scheme:dark}"]
    return "\n".join(o) + "\n"
def check():
    src = (root / "games/dead-reckoning/index.src.html").read_text()
    m = re.search(r":root\{(.*?)\}", src, re.S); d = re.search(r":root\[data-theme=dark\]\{(.*?)\}", src)
    bad = 0
    for name, text, key in (("light", m.group(1), "light"), ("dark", d.group(1), "dark")):
        for k, v in T["color"].items():
            if not v["existing"]: continue
            g = re.search(r"--%s:\s*(#[0-9a-fA-F]{6})" % re.escape(k), text)
            if not g or g.group(1).lower() != v[key].lower():
                print(f"drift {name} --{k}: game={g.group(1) if g else 'missing'} token={v[key]}"); bad += 1
    print("tokens match the game" if not bad else f"{bad} drift(s)"); return bad
if "--check" in sys.argv: sys.exit(1 if check() else 0)
(root / "design/tokens.css").write_text(css()); print("wrote design/tokens.css")
